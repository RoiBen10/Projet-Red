// isWalkable --> vrai si la tuile à (x, y) est praticable (herbe ou chemin).
func isWalkable(x, y int) bool {
	if y < 0 || y >= len(worldMap) || x < 0 || x >= len(worldMap[y]) {
		return false
	}
	switch worldMap[y][x] {
	case '.', ',':
		return true
	default:
		return false
	}
}
